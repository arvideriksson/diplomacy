// Shared finishing steps of the generated boards: the dSVG file (layer order and data layers the
// app reads), hand placements from the layout editor, the draft gates, and the MapDefinition.
import { readFileSync, writeFileSync } from 'node:fs'
import { fileURLToPath } from 'node:url'
import { dirname, resolve } from 'node:path'
import { supplyCenterLayer } from '../1900/artwork.mjs'

export const root = resolve(dirname(fileURLToPath(import.meta.url)), '../../..')

export const r1 = (n) => Math.round(n * 10) / 10
const layer = (id, body, extra = '') => `<g id="${id}"${extra}>\n${body}\n</g>`
const hidden = ' style="display:none"'
// The coast shading and water-lining reach past the board edge; clip the artwork to the board.
const clipped = (body) => `<g clip-path="url(#board-clip)">\n${body}\n</g>`

/**
 * Write a board's dSVG (`public/maps/<name>.dsvg`). `board` is drawBoard's result. Ids are dSVG
 * ids already: `provinces` and `namedCoasts` are [id, pathData] pairs, `units` [id, [x, y]]
 * pairs, `routes` (optional layer) [id, legs] pairs, each leg a polyline. `centers` maps
 * province ids to points, written under `centerId(id)`. `extraDefs` goes into <defs>.
 */
export function writeBoard(name, { width, height, board, background = board.background, extraDefs = '', provinces, namedCoasts = [], centers, centerId, units, routes }) {
  const defs = board.defs.replace('</defs>', `${extraDefs}<clipPath id="board-clip"><rect width="${width}" height="${height}"/></clipPath></defs>`)
  const paths = (list) => list.map(([id, d]) => `<path id="${id}" d="${d}"/>`)
  const svg = [
    `<svg xmlns="http://www.w3.org/2000/svg" xmlns:xlink="http://www.w3.org/1999/xlink" viewBox="0 0 ${width} ${height}" width="100%" height="100%">`,
    defs,
    layer('background', clipped(background)),
    layer('provinces', paths(provinces).join('\n'), hidden),
    layer('named-coasts', paths(namedCoasts).join('\n'), hidden),
    supplyCenterLayer(centers, centerId),
    layer('unit-positions', units.map(([id, [x, y]]) => `<circle id="${id}" cx="${r1(x)}" cy="${r1(y)}"/>`).join(''), hidden),
    layer('province-names', board.names),
    ...(routes ? [layer('routes', routes.map(([id, legs]) => `<path id="${id}" d="${legs.map((leg) => 'M' + leg.map((p) => p.map(r1).join(' ')).join('L')).join('')}"/>`).join(''), hidden)] : []),
    '<g id="borders"/>',
    layer('foreground', clipped(board.foreground)),
    '</svg>',
    '',
  ].join('\n')
  writeFileSync(resolve(root, `public/maps/${name}.dsvg`), svg)
}

/** Write `src/lib/maps/<name>.ts`, exporting `map` as `exportName`. */
export function writeMapDefinition(name, exportName, map) {
  writeFileSync(resolve(root, `src/lib/maps/${name}.ts`), `import type { MapDefinition } from '../mapDefinition'\n\n// Generated by tools/variants/${name}/build.mjs. Do not edit by hand.\nexport const ${exportName}: MapDefinition = ${JSON.stringify(map, null, 2)}\n`)
}

/**
 * Problems that make a board unfit to ship fail the build, unless the environment variable
 * `draftVar` is set (for iterating on a draft), when they are only printed.
 */
export function failUnlessDraft(problems, heading, draftVar) {
  if (!problems.length) return
  const message = `${heading}:\n  ${problems.join('\n  ')}`
  if (process.env[draftVar]) console.warn(message)
  else throw new Error(message)
}

/** Hand placements from the layout editor (/editor), keyed by dSVG id: { units, centers, labels }. */
export const readPlacements = (dir) => ({ units: {}, centers: {}, labels: {}, ...JSON.parse(readFileSync(resolve(dir, 'placements.json'), 'utf8')) })

/**
 * Check hand placements against what the board has. `known` holds the dSVG ids of the board's
 * unit anchors, supply centers and labels (iterables); a placement for anything else throws (a
 * renamed or removed province would otherwise be dropped silently). `inside(unitId, point)`
 * says whether a point lies in a unit anchor's province: returns a problem for each pinned unit
 * outside it, for the caller's layout gate.
 */
export function checkPlacements(placements, known, inside) {
  const kinds = { units: 'unit anchor', centers: 'supply center', labels: 'label' }
  const unknown = Object.entries(kinds).flatMap(([k, what]) => {
    const ids = new Set(known[k])
    return Object.keys(placements[k]).filter((id) => !ids.has(id)).map((id) => `no ${what} ${id}`)
  })
  if (unknown.length) throw new Error(`placements.json: ${unknown.join(', ')}`)
  return Object.entries(placements.units).filter(([id, pt]) => !inside(id, pt)).map(([id]) => `placements.json: ${id} lies outside its province`)
}
